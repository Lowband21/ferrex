#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SystemCollectionDefinition {
    pub stable_key: String,
    pub shelf: SystemDiscoveryShelf,
    pub section_id: String,
    pub title: String,
    pub reason: Option<String>,
    pub layout_hint: DiscoveryLayoutHint,
    pub scope: CollectionScope,
    pub media_scope: CollectionMediaScope,
    pub rule: DynamicCollectionRule,
    pub placement: SystemShelfPlacementDefinition,
}

impl SystemCollectionDefinition {
    pub fn owner(&self) -> CollectionOwner {
        CollectionOwner {
            owner_type: CollectionOwnerType::System,
            user_id: None,
            device_id: None,
            display_name: Some("Ferrex".to_string()),
        }
    }

    pub const fn kind(&self) -> super::collections::CollectionKind {
        super::collections::CollectionKind::System
    }

    pub const fn source(&self) -> CollectionSource {
        CollectionSource::System
    }

    pub const fn visibility(&self) -> CollectionVisibility {
        CollectionVisibility::System
    }

    pub const fn presentation(&self) -> CollectionPresentationMode {
        CollectionPresentationMode::Shelf
    }

    pub const fn duplicate_policy(&self) -> CollectionDuplicatePolicy {
        CollectionDuplicatePolicy::DeduplicateMedia
    }

    pub fn description(&self) -> String {
        self.reason.clone().unwrap_or_else(|| self.title.clone())
    }

    pub fn provenance(&self) -> CollectionProvenance {
        CollectionProvenance {
            source: CollectionSource::System,
            external_id: Some(self.stable_key.clone()),
            generated_by: Some(SYSTEM_DISCOVERY_GENERATOR.to_string()),
            rule_hash: self.rule.rule_hash().ok(),
            ..CollectionProvenance::default()
        }
    }

    pub fn library_id(&self) -> Option<LibraryId> {
        match &self.media_scope {
            CollectionMediaScope::Library { library_id, .. } => {
                Some(*library_id)
            }
            _ => None,
        }
    }

    pub fn section(
        &self,
        items: Vec<DiscoveryItem>,
        requested_limit: usize,
    ) -> DiscoverySection {
        DiscoverySection::new(
            self.section_id.clone(),
            self.title.clone(),
            self.reason.clone(),
            self.layout_hint,
            items,
            requested_limit,
        )
    }
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Hash)]
#[serde(rename_all = "snake_case")]
pub enum SystemCollectionStaleCause {
    Catalog,
    Metadata,
    WatchState,
    Rule,
}

impl SystemCollectionStaleCause {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Catalog => "catalog",
            Self::Metadata => "metadata",
            Self::WatchState => "watch_state",
            Self::Rule => "rule",
        }
    }

    pub const fn stale_reason(self) -> &'static str {
        match self {
            Self::Catalog => "system discovery catalog change",
            Self::Metadata => "system discovery metadata change",
            Self::WatchState => "system discovery watch-state change",
            Self::Rule => "system discovery rule change",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MarkSystemCollectionsStaleRequest {
    pub cause: SystemCollectionStaleCause,
    pub library_id: Option<LibraryId>,
    pub user_id: Option<Uuid>,
}

impl MarkSystemCollectionsStaleRequest {
    pub const fn catalog(library_id: Option<LibraryId>) -> Self {
        Self {
            cause: SystemCollectionStaleCause::Catalog,
            library_id,
            user_id: None,
        }
    }

    pub const fn metadata(library_id: Option<LibraryId>) -> Self {
        Self {
            cause: SystemCollectionStaleCause::Metadata,
            library_id,
            user_id: None,
        }
    }

    pub const fn watch_state(
        user_id: Uuid,
        library_id: Option<LibraryId>,
    ) -> Self {
        Self {
            cause: SystemCollectionStaleCause::WatchState,
            library_id,
            user_id: Some(user_id),
        }
    }
}

