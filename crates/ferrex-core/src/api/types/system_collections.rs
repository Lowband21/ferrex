//! Stable system collection templates backing deterministic discovery shelves.
//!
//! These definitions bridge the current `/api/v1/discovery/*` shelves to the
//! dynamic collection substrate without changing the response shape. Each
//! definition carries the section metadata clients already consume plus the
//! dynamic rule, sort, limit, and shelf placement metadata needed to seed or
//! refresh a backing system collection.

use ferrex_model::{LibraryId, LibraryType};
use serde::{Deserialize, Serialize};
